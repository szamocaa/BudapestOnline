/** Approximate star colour (linear RGB, max 1) from the B-V index. */
export function starColour(bv) {
	const t = Math.max(-0.4, Math.min(2.0, bv));
	// Blue-white (-0.3) → white (0.3) → yellow (0.8) → orange-red (1.8)
	const r = t < 0.3 ? 0.62 + (t + 0.4) * 0.54 : 1.0;
	const g = t < 0.3 ? 0.75 + (t + 0.4) * 0.36 : Math.max(0.42, 1.0 - (t - 0.3) * 0.36);
	const b = t < 0.3 ? 1.0 : Math.max(0.12, 1.0 - (t - 0.3) * 0.62);
	return [r, g, b];
}

/** Equatorial unit vector for right ascension (hours) and declination (degrees). */
export function equatorialVector(raHours, decDeg) {
	const a = (raHours / 24) * Math.PI * 2, d = (decDeg * Math.PI) / 180;
	return [Math.cos(d) * Math.cos(a), Math.cos(d) * Math.sin(a), Math.sin(d)];
}
